export function seedIfEmpty() {
  const db = getDB();
  // 默认设置（仅缺省时写入）
  const defaults = {
    title: '梁老师的学生成长档案',
    teacher_name: '梁老师',
    theme_id: 'fresh',
    stage_filter: 'all',
    calendar_api_base: 'http://127.0.0.1:8787',
    calendar_semester_id: '',
    calendar_link_enabled: true,
  };
  for (const [k, v] of Object.entries(defaults)) {
    const row = db.prepare('SELECT key FROM settings WHERE key = ?').get(k);
    if (!row) setSetting(k, v);
  }
  // 知识库种子（幂等增量：按 id 去重，新条目自动补入，不重复插入）
  const db2 = db;
  const existing = new Set(db2.prepare('SELECT id FROM knowledge_items').all().map((r) => r.id));
  const items = [...CLASSIC, ...PSYCHOLOGY, ...MASTER, ...QUOTE];
  const toInsert = items.filter((it) => !existing.has(it.id));
  if (toInsert.length) {
    db2.exec('BEGIN');
    try {
      for (const it of toInsert) insertRow('knowledge_items', it);
      db2.exec('COMMIT');
    } catch (e) {
      db2.exec('ROLLBACK');
      throw e;
    }
  }
  return { seeded: true, knowledge_count: CLASSIC.length + PSYCHOLOGY.length + MASTER.length + QUOTE.length, inserted: toInsert.length };
}
